function getAurexLang() {
  var lang = localStorage.getItem('aurex_lang') || 'pt';
  return TRANSLATIONS[lang] ? lang : 'pt';
}

// t(key): retorna a string traduzida para uso em JS dinâmico
function t(key) {
  var lang = getAurexLang();
  var dict = TRANSLATIONS[lang] || TRANSLATIONS.pt;
  return dict[key] || TRANSLATIONS.pt[key] || key;
}

// Aplica o idioma a todos os elementos com data-i18n / data-i18n-ph
function applyLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'pt';
  localStorage.setItem('aurex_lang', lang);
  try {
    if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
      chrome.storage.local.set({ aurex_lang: lang });
    }
  } catch (e) { /* ignore */ }

  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    var value = t(key);
    if (value) el.textContent = value;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-ph');
    var value = t(key);
    if (value) el.setAttribute('placeholder', value);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-title');
    var value = t(key);
    if (value) el.setAttribute('title', value);
  });
}

// Diretiva de idioma para o system prompt
function getLanguageDirective() {
  var lang = getAurexLang();
  var name = AUREX_LANG_PROMPT_NAME[lang] || AUREX_LANG_PROMPT_NAME.pt;
  return "\n\n# IDIOMA\nResponda e aja SEMPRE em " + name + ", incluindo widgets, planos e mensagens. Mesmo que a pergunta venha em outro idioma, responda em " + name + ".";
}
